import React from 'react';
import {MemoryRouter} from 'react-router-dom';
import {act,mount,until} from '../testUtils';
import WatchlistPage from './WatchlistPage';
import LibraryPage from './LibraryPage';
import {api} from '../lib/api';
let mockApp;
jest.mock('../context/AppContext',()=>({useApp:()=>mockApp}));
jest.mock('../lib/api',()=>({api:{post:jest.fn()},IS_CAPACITOR_OFFLINE:true,errMsg:e=>e.message}));
jest.mock('../lib/useExperience',()=>({useExperience:section=>require('react').useState(require('../lib/collectionModel').collectionPreferences(section))}));
jest.mock('../lib/useAvailability',()=>({useAvailability:()=>[{},()=>{}]}));
jest.mock('../components/PosterCard',()=>({item,hideWatchlistMarker})=><a href={`/title/${item.type}/${item.imdb_id}`} data-marker-hidden={hideWatchlistMarker}>{item.name}</a>);
jest.mock('../components/FilesSheet',()=>({t})=>t?<div data-testid="files-open">{t.name}</div>:null);
jest.mock('../components/AddMagnetDialog',()=>()=>null);
jest.mock('../components/ShareCreateDialog',()=>()=>null);
let view;
beforeEach(()=>{mockApp={key:'fixture-only',session:{scope:Math.random()},watchlist:[{imdb_id:'tt1',name:'Alpha',type:'movie',year:2025},{imdb_id:'tt2',name:'Beta',type:'series',year:2024}],tracking:new Map(),refreshWatchlist:jest.fn().mockResolvedValue(),library:[{id:1,name:'Film.2025.1080p',download_finished:true,files:[]},{id:2,name:'Show.S01.1080p',download_finished:true,files:[]}],refreshLibrary:jest.fn().mockResolvedValue()};});
afterEach(async()=>{if(view)await view.close();view=null;jest.clearAllMocks();});
test('Watchlist search clears without losing saved titles and layout is interactive',async()=>{
 view=await mount(<MemoryRouter><WatchlistPage/></MemoryRouter>);
 expect(view.container.textContent).toContain('2 saved titles');
 await act(async()=>view.container.querySelector('[aria-label="List view"]').click());
 expect(view.container.querySelector('[data-testid="watchlist-grid"]').getAttribute('data-layout')).toBe('list');
 const input=view.container.querySelector('[aria-label="Search watchlist"]');
 await act(async()=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'nothing matches');input.dispatchEvent(new Event('input',{bubbles:true}));});
 expect(view.container.textContent).toContain('No matching titles');expect(mockApp.watchlist).toHaveLength(2);
 await act(async()=>[...view.container.querySelectorAll('button')].find(button=>button.textContent==='Clear filters').click());
 expect(view.container.querySelectorAll('a[href^="/title/"]')).toHaveLength(2);
 expect(view.container.querySelectorAll('[data-marker-hidden="true"]')).toHaveLength(2);
});
test('TorBox opens files normally and selection uses real IDs, with partial failures retained',async()=>{
 api.post.mockResolvedValue({data:[{id:1,ok:true},{id:2,ok:false,error:'Unable to reannounce'}]});
 view=await mount(<MemoryRouter><LibraryPage/></MemoryRouter>);
 expect(view.container.querySelector('[role="checkbox"]')).toBeNull();
 await act(async()=>view.container.querySelector('[data-testid="library-open-0"]').click());expect(view.container.querySelector('[data-testid="files-open"]')).not.toBeNull();
 await act(async()=>[...view.container.querySelectorAll('button')].find(button=>button.textContent==='Select').click());
 expect(view.container.querySelectorAll('[role="checkbox"]')).toHaveLength(2);
 await act(async()=>view.container.querySelector('[data-testid="library-select-all"]').click());
 expect(document.querySelector('[data-testid="bulk-selected-count"]').textContent).toBe('2');
 await act(async()=>document.querySelector('[data-testid="reannounce-selected-button"]').click());
 await until(()=>document.querySelector('[data-testid="bulk-selected-count"]')?.textContent==='1');
 expect(api.post).toHaveBeenCalledWith('/torbox/control',{torrent_ids:[1,2],operation:'reannounce'});
 expect(view.container.querySelector('[data-testid="library-select-1"]').getAttribute('aria-checked')).toBe('true');
});
