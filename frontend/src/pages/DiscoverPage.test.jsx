import React from 'react';
import {MemoryRouter} from 'react-router-dom';
import {act,mount,until} from '../testUtils';
import DiscoverPage from './DiscoverPage';
import {api} from '../lib/api';
jest.mock('../lib/api',()=>({api:{get:jest.fn()},errMsg:error=>error.message}));
jest.mock('../context/AppContext',()=>({useApp:()=>({tracking:new Map(),catalog:{items:[]}})}));
jest.mock('../lib/useExperience',()=>{const React=require('react');return {useExperience:()=>React.useState({type:'movie',region:'HU',category:'popular',filters:{genre:'',year_from:'',year_to:'',imdb_rating:'',provider:'',sort:'',language:'',certification:''},hideWatched:false,hideLibrary:false})};});
jest.mock('./SearchPage',()=>()=>null);
jest.mock('../components/PosterCard',()=>({item})=><a href={`/title/${item.type}/${item.id}`}>{item.name}</a>);
let view;
beforeEach(()=>{api.get.mockImplementation(async(path,config)=>({data:path==='/discover/providers'?{providers:[{id:8,name:'Netflix',logo:'https://example.invalid/netflix.jpg'},{id:119,name:'Prime Video',logo:'https://example.invalid/prime.jpg'}]}:path==='/meta/genres'?{movie:[{id:18,name:'Drama'}],series:[]}:path==='/discover/tmdb'?{items:[{id:String(config.params.page),name:`Page ${config.params.page}`,type:'movie'}],page:config.params.page,total_pages:2}:{items:[]}}));});
afterEach(async()=>{if(view)await view.close();view=null;jest.clearAllMocks();});
test('unified provider/channel controls reach the real query and can be cleared without changing pages',async()=>{
 view=await mount(<MemoryRouter initialEntries={['/discover']}><DiscoverPage/></MemoryRouter>);
 await until(()=>view.container.querySelector('[aria-label="Netflix"]')?.disabled===false);
 expect([...view.container.querySelectorAll('button')].some(button=>['Browse','Services'].includes(button.textContent))).toBe(false);
 await act(async()=>view.container.querySelector('[aria-label="Netflix"]').click());
 await until(()=>api.get.mock.calls.some(([path,c])=>path==='/discover/tmdb' && c.params.provider==='8'));
 expect(api.get.mock.calls.some(([path,c])=>path==='/discover/tmdb' && c.params.region==='HU')).toBe(true);
 await act(async()=>[...view.container.querySelectorAll('button')].find(button=>button.textContent==='Top rated').click());
 await until(()=>api.get.mock.calls.some(([path,c])=>path==='/discover/tmdb' && c.params.category==='top' && c.params.provider==='8'));
 await until(()=>[...view.container.querySelectorAll('button')].some(button=>button.textContent==='Load more'));
 await act(async()=>[...view.container.querySelectorAll('button')].find(button=>button.textContent==='Load more').click());
 await until(()=>api.get.mock.calls.some(([path,c])=>path==='/discover/tmdb' && c.params.page===2 && c.params.provider==='8'));
 await act(async()=>view.container.querySelector('[aria-label="Netflix"]').click());
 await until(()=>view.container.querySelector('[aria-label="Netflix"]').getAttribute('aria-pressed')==='false');
 expect(view.container.textContent).toContain('All services');
});

test('filter sheet retains an unapplied draft, applies library switches together, and resets real filters',async()=>{
 view=await mount(<MemoryRouter initialEntries={['/discover']}><DiscoverPage/></MemoryRouter>);
 await until(()=>view.container.querySelector('[data-testid="discover-results-catalog"]'));
 await act(async()=>view.container.querySelector('[data-testid="open-filters-button"]').click());
 const dialog=()=>document.querySelector('[data-testid="discovery-filters-sheet"]');
 await until(()=>dialog());
 await act(async()=>dialog().querySelector('[aria-label="Hide watched"]').click());
 expect(view.container.querySelector('[aria-label="Active Discover filters"]')).toBeNull();
 await act(async()=>dialog().querySelector('[aria-label="Close dialog"]').click());
 await act(async()=>view.container.querySelector('[data-testid="open-filters-button"]').click());
 expect(dialog().querySelector('[aria-label="Hide watched"]').getAttribute('aria-checked')).toBe('true');
 await act(async()=>dialog().querySelector('[aria-label="Hide known library titles"]').click());
 await act(async()=>[...dialog().querySelectorAll('button')].find(button=>button.textContent==='Show results').click());
 await until(()=>view.container.querySelector('[aria-label="Remove Hide watched filter"]'));
 expect(view.container.querySelector('[aria-label="Remove Hide library titles filter"]')).not.toBeNull();
 await act(async()=>view.container.querySelector('[data-testid="open-filters-button"]').click());
 await act(async()=>[...dialog().querySelectorAll('button')].find(button=>button.textContent==='Reset filters').click());
 await act(async()=>[...dialog().querySelectorAll('button')].find(button=>button.textContent==='Show results').click());
 await until(()=>!view.container.querySelector('[aria-label="Active Discover filters"]'));
});
test('all-services picker searches and selects the real provider ID',async()=>{
 view=await mount(<MemoryRouter initialEntries={['/discover']}><DiscoverPage/></MemoryRouter>);
 await until(()=>view.container.querySelector('[aria-label="Netflix"]'));
 await act(async()=>view.container.querySelector('[aria-label="All services"]').click());
 const dialog=document.querySelector('[data-testid="discovery-services-sheet"]');
 await act(async()=>[...dialog.querySelectorAll('button')].find(button=>button.textContent==='Prime Video').click());
 await until(()=>api.get.mock.calls.some(([path,c])=>path==='/discover/tmdb' && c.params.provider==='119'));
 expect(view.container.querySelector('[aria-label="Prime Video"]').getAttribute('aria-pressed')).toBe('true');
 await act(async()=>view.container.querySelector('[aria-label="Prime Video"]').click());
 await until(()=>view.container.querySelector('[aria-label="Prime Video"]').getAttribute('aria-pressed')==='false');
});
