/* Real production UI with intercepted provider fixtures; never a live-provider claim. */
const fs=require('fs');
module.exports=async({page,width,theme,assert})=>{
  const button=name=>page.getByRole('button',{name,exact:true});
  const shot=async name=>{
    const filename=`discover-${name}-${width}-${theme}.png`;
    const bytes=await page.screenshot({path:`../artifacts/${filename}`});
    // Reusable connector evidence: binary artifacts cannot be read by this executor.
    if(width===360 && ['browse','filters'].includes(name))console.log(`STAK_DISCOVER_SCREENSHOT ${filename} ${bytes.toString('base64')}`);
  };
  if(await button('Reset all').count())await button('Reset all').click();
  await page.getByTestId('discover-results-catalog').waitFor();
  await page.evaluate(()=>scrollTo(0,0));
  await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.evaluate(()=>document.fonts.check('900 32px Doto')),true,'Doto font must load locally');
  assert.equal(await page.getByTestId('open-filters-button').count(),1);
  assert.equal(await page.getByRole('combobox',{name:'More streaming services',exact:true}).count(),0);
  const grid=page.getByTestId('discover-results-catalog');
  assert.equal(await grid.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),3);
  const bounds=await grid.boundingBox();assert.ok(bounds.y<530,'Artwork must appear without a long controls wall');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
  const titleStyle=await grid.locator('.poster-title').first().evaluate(el=>({lines:getComputedStyle(el).webkitLineClamp,font:getComputedStyle(el).fontFamily}));
  assert.equal(titleStyle.lines,'2');assert.ok(titleStyle.font.includes('Hanken'));
  const navLinks=page.getByRole('navigation',{name:'Main navigation'}).getByRole('link');
  assert.equal(await navLinks.count(),6);
  for(const name of ['Home','Discover','Watchlist','Tracking','Library','Settings'])assert.equal(await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name,exact:true}).count(),1);
  assert.equal(await navLinks.locator('.stak-nav-label:visible').count(),await navLinks.count(),'Every navigation label stays visible');
  const titleGaps=await grid.locator('.media-poster').evaluateAll(cards=>cards.map(card=>{const title=card.querySelector('.poster-title'),meta=card.querySelector('.poster-meta');return meta.getBoundingClientRect().top-title.getBoundingClientRect().bottom;}));
  assert.ok(titleGaps.every(gap=>gap>=0 && gap<=6),'Years sit directly below the actual title, without a reserved blank line');
  await shot('browse');
  await page.getByTestId('open-filters-button').click();
  const sheet=page.getByTestId('discovery-filters-sheet');await sheet.waitFor();
  assert.equal(await sheet.getByRole('heading',{name:'Filters'}).count(),1);
  assert.equal(await page.locator('nav[aria-label="Main navigation"]').evaluate(el=>Boolean(el.closest('[aria-hidden="true"]'))),true);
  const footer=sheet.locator('.discovery-sheet-footer');
  assert.ok((await footer.boundingBox()).y+ (await footer.boundingBox()).height<=880);
  await shot('filters');
  await sheet.getByLabel('Find a language',{exact:true}).fill('Hungarian');
  await sheet.getByRole('combobox',{name:'Original language',exact:true}).click();
  await page.getByRole('option',{name:'Hungarian · HU',exact:true}).click();
  await sheet.getByRole('switch',{name:'Hide watched',exact:true}).click();
  await sheet.getByLabel('From year',{exact:true}).fill('2030');await sheet.getByLabel('To year',{exact:true}).fill('2020');
  assert.equal(await button('Show results').isDisabled(),true);
  await sheet.getByLabel('From year',{exact:true}).fill('2010');
  await sheet.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByTestId('open-filters-button').click();
  assert.equal(await sheet.getByRole('switch',{name:'Hide watched',exact:true}).isChecked(),true);
  assert.equal(await sheet.getByRole('combobox',{name:'Original language',exact:true}).textContent().then(s=>s.includes('Hungarian')),true);
  await button('Show results').click();
  await button('Remove HU filter').waitFor();await button('Remove Hide watched filter').waitFor();
  await button('Reset all').click();
  await button('All services').click();
  const serviceSheet=page.getByTestId('discovery-services-sheet');
  await serviceSheet.getByLabel('Search streaming services',{exact:true}).fill('Amazon');
  await serviceSheet.getByRole('button',{name:'Amazon Prime Video',exact:true}).click();
  assert.equal(await button('Prime Video').getAttribute('aria-pressed'),'true');
  await button('Prime Video').click();
  await page.getByRole('combobox',{name:'Sort',exact:true}).click();
  await page.getByRole('option',{name:'Newest first',exact:true}).click();
  await button('Remove Custom order filter').waitFor();
  await button('Reset all').click();
  await page.evaluate(()=>document.documentElement.dataset.compact='true');
  assert.equal(await grid.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),3);
  await shot('compact');
  await page.evaluate(()=>document.documentElement.dataset.compact='false');
  await grid.locator('a').last().scrollIntoViewIfNeeded();
  const last=await grid.locator('a').last().boundingBox(),nav=await page.getByRole('navigation',{name:'Main navigation'}).boundingBox();
  // Scroll to the end so the last poster can clear the floating navigation.
  await page.evaluate(()=>scrollTo(0,document.documentElement.scrollHeight));
  const end=await grid.locator('a').last().boundingBox();assert.ok(end.y+end.height<=nav.y,'Final poster must clear navigation');
  assert.ok(last.height>0);
  fs.mkdirSync('../validation',{recursive:true});
  fs.writeFileSync(`../validation/discover-${width}-${theme}.json`,JSON.stringify({width,theme,fixtureProviders:true,gridColumns:3,compactColumns:3,posterTop:bounds.y,languagePicker:true,draftPersistence:true,yearValidation:true,serviceProviderIds:true,sort:true,navClearance:true,fonts:'local',screenshots:[`discover-browse-${width}-${theme}.png`,`discover-filters-${width}-${theme}.png`,`discover-compact-${width}-${theme}.png`]},null,2));
};
